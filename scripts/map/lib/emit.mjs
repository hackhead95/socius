/** In Markdown table rows, a wikilink's alias pipe must be escaped (\\|) or it splits the cell. */
export function escapeTableLinks(text) {
  return text
    .split('\n')
    .map((l) => (l.startsWith('|') ? l.replace(/\[\[([^\]|]*?)\|([^\]]*?)\]\]/g, '[[$1\\|$2]]') : l))
    .join('\n');
}

export const sanitize = (s) =>
  String(s)
    .replace(/[\\/:*?"<>|#^[\]]/g, '-')
    .replace(/\s+/g, ' ')
    .replace(/[. ]+$/, '')
    .trim() || '_';

/** Assigns every node a note path (or a heading inside its module's note, or nothing). */
export class Notes {
  constructor(g) {
    this.g = g;
    this.paths = new Map();
    const used = new Map();
    const claim = (id, p) => {
      // never shadow the top-level notes (README, Home, GRAPH_REPORT, DIAGRAMS)
      if (RESERVED.has(p.split('/').pop().toLowerCase())) p = `${p} (${g.get(id)?.type ?? 'note'})`;
      let q = p;
      let i = 2;
      while (used.has(q.toLowerCase())) q = `${p} (${i++})`;
      used.set(q.toLowerCase(), id);
      this.paths.set(id, q);
    };
    const nodes = g.sortedNodes();
    // components and hooks: disambiguate by folder when names clash
    const nameCount = new Map();
    for (const n of nodes) if (n.type === 'component' || n.type === 'hook' || n.type === 'ai-prompt') nameCount.set(`${n.type}|${n.label}`, (nameCount.get(`${n.type}|${n.label}`) ?? 0) + 1);
    const where = (n) => (n.file ?? '').replace(/^src\//, '').replace(/\.[jt]sx?$/, '').replace(/\//g, '-');
    for (const n of nodes) {
      if (!NOTE_TYPES.has(n.type)) continue;
      if (n.type === 'store' && !n.id.startsWith('settings:') && !n.id.startsWith('sym:')) continue;
      let p;
      switch (n.type) {
        case 'area':
          p = `Areas/${sanitize(n.label.replace(/\//g, ' - '))}`;
          break;
        case 'module':
        case 'test':
        case 'test-helper':
        case 'e2e-spec':
          p = `Code/${n.file.split('/').map(sanitize).join('/')}`;
          break;
        case 'component':
          p = `Components/${sanitize(n.label)}${nameCount.get(`component|${n.label}`) > 1 ? ` (${where(n)})` : ''}`;
          break;
        case 'hook':
          p = `Hooks/${sanitize(n.label)}${nameCount.get(`hook|${n.label}`) > 1 ? ` (${where(n)})` : ''}`;
          break;
        case 'store':
          p = `Store/${sanitize(n.id.startsWith('settings:') ? n.id.slice(9) : n.label)}`;
          break;
        case 'store-key':
          p = `Store/${sanitize(n.store)}/${sanitize(n.label.split('.').slice(1).join('.'))}`;
          break;
        case 'store-action':
          p = `Store/${sanitize(n.store)}/${sanitize(n.label.split('.').slice(1).join('.'))}`;
          break;
        case 'menu':
          p = `Menus/${sanitize(n.label)}`;
          break;
        case 'submenu':
        case 'command':
          p = `Menus/${(n.path ?? n.label).split(' > ').map(sanitize).join('/')}`;
          break;
        case 'dialog':
          p = `Dialogs/${sanitize(n.kind)}/${sanitize(n.dialogId)}`;
          break;
        case 'dialog-kind':
          p = `Dialogs/${sanitize(n.id.split(':')[1])} dialogs`;
          break;
        case 'shortcut':
          p = `Shortcuts/${sanitize(n.label)}`;
          break;
        case 'procedure':
          p = `Procedures/${sanitize(n.procedureId)}`;
          break;
        case 'transform':
          p = `Transforms/${sanitize(n.label)}`;
          break;
        case 'syntax':
          p = `Syntax/${sanitize(n.label)}`;
          break;
        case 'ai-provider':
          p = `AI/Providers/${sanitize(n.label)}`;
          break;
        case 'ai-feature':
          p = `AI/Features/${sanitize(n.id.split(':')[1])}`;
          break;
        case 'ai-error':
          p = `AI/Errors/${sanitize(n.label)}`;
          break;
        case 'ai-tool':
          p = `AI/Tools/${sanitize(n.label)}`;
          break;
        case 'ai-prompt':
          p = `AI/Prompts/${sanitize(n.label)}${nameCount.get(`ai-prompt|${n.label}`) > 1 ? ` (${where(n)})` : ''}`;
          break;
        case 'storage-key':
          p = `Storage/${sanitize(n.backend)}/${sanitize(n.label)}`;
          break;
        case 'output-kind':
          p = `Output/Blocks/${sanitize(n.label)}`;
          break;
        case 'chart-type':
          p = `Output/Charts/${sanitize(n.label)}`;
          break;
        case 'output-source':
          p = `Output/Sources/${sanitize(n.id.split(':')[1])}`;
          break;
        case 'palette-source':
          p = `Palette/${sanitize(n.id.split(':')[1])}`;
          break;
        case 'package':
          p = `Packages/${sanitize(n.label)}`;
          break;
        default:
          continue;
      }
      claim(n.id, p);
    }
  }

  /** Shortest path suffix that identifies a note uniquely (Obsidian resolves links by path suffix). */
  short(p) {
    if (!this.shortCache) {
      this.shortCache = new Map();
      const all = [...this.paths.values()];
      const suffixes = new Map();
      for (const q of all) {
        const parts = q.split('/');
        for (let i = 0; i < parts.length; i++) {
          const suf = parts.slice(i).join('/').toLowerCase();
          suffixes.set(suf, (suffixes.get(suf) ?? 0) + 1);
        }
      }
      for (const q of all) {
        const parts = q.split('/');
        let best = q;
        for (let i = parts.length - 1; i >= 0; i--) {
          const suf = parts.slice(i).join('/');
          if (suffixes.get(suf.toLowerCase()) === 1 && !RESERVED.has(suf.toLowerCase())) {
            best = suf;
            break;
          }
        }
        this.shortCache.set(q, best);
      }
    }
    return this.shortCache.get(p) ?? p;
  }

  /** A wikilink for a node id (note, heading in a module note, or inline code when it has no note). */
  link(id, alias) {
    const n = this.g.get(id);
    const p = this.paths.get(id);
    // modules read best as their short path, which is also the link target
    if (p && !alias && n && MODULE_TYPES.has(n.type)) return `[[${this.short(p)}]]`;
    const text = (alias ?? displayName(n, id)).replace(/[|[\]]/g, '/');
    if (p) return this.short(p) === text ? `[[${text}]]` : `[[${this.short(p)}|${text}]]`;
    const folded = this.g.folded?.(id);
    if (folded) {
      const mp = this.paths.get(`module:${folded.file}`);
      const t2 = (alias ?? `${folded.label}${folded.type === 'function' ? '()' : ''}`).replace(/[|[\]]/g, '/');
      if (mp) return `[[${this.short(mp)}|${t2}]]`;
    }
    if (n && HEADING_TYPES.has(n.type) && n.file) {
      const mp = this.paths.get(`module:${n.file}`);
      if (mp) return `[[${this.short(mp)}#${n.label}|${text}]]`;
    }
    return `\`${text}\``;
  }

  /** Replace [[nodeId]] tokens (from the analysis) with real links. */
  resolveTokens(s) {
    return s.replace(/\[\[([a-z][a-z-]*:[^\]|]+)\]\]/g, (m, id) => (this.g.has(id) || this.g.folded?.(id) ? this.link(id) : `\`${id.replace(/^[a-z-]+:/, '')}\``));
  }
}

export function displayName(n, id) {
  if (!n) return id.replace(/^[a-z-]+:/, '');
  switch (n.type) {
    case 'module':
    case 'test':
    case 'test-helper':
    case 'e2e-spec':
      return n.file;
    case 'command':
    case 'submenu':
      return n.path ?? n.label;
    case 'function':
    case 'hook':
      return `${n.label}()`;
    case 'component':
      return `<${n.label}>`;
    default:
      return n.label;
  }
}

function yamlStr(v) {
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  const s = String(v);
  return /^[\w./@-]+$/.test(s) && !/^(true|false|null|yes|no|on|off|\d.*)$/i.test(s) ? s : JSON.stringify(s);
}

function frontMatter(n, extra = {}) {
  const lines = ['---'];
  const fm = { id: jsonId(n.id), type: n.type, file: n.file, line: n.line, area: n.area, ...extra };
  for (const [k, v] of Object.entries(fm)) {
    if (v === undefined || v === null || v === '') continue;
    if (Array.isArray(v)) lines.push(`${k}: [${v.map(yamlStr).join(', ')}]`);
    else lines.push(`${k}: ${yamlStr(v)}`);
  }
  lines.push('---', '');
  return lines.join('\n');
}

